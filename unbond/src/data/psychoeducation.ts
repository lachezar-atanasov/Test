// Get a random insight for today
export function getTodayInsight(): typeof dailyInsights[0] {
  const today = new Date().toISOString().split('T')[0];
  // Use the date as a seed for "randomness" that stays consistent for the day
  const hash = today.split('').reduce((acc, char) => acc + char.charCodeAt(0), 0);
  const index = hash % dailyInsights.length;
  return dailyInsights[index];
}

// Get articles by category
export function getArticlesByCategory(category: Article['category']): Article[] {
  return articles.filter((article) => article.category === category);
}

// Search articles
export function searchArticles(query: string): Article[] {
  const lowerQuery = query.toLowerCase();
  return articles.filter(
    (article) =>
      article.title.toLowerCase().includes(lowerQuery) ||
      article.content.toLowerCase().includes(lowerQuery)
  );
}
